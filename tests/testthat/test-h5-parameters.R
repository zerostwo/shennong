test_that("10x H5 import preserves requested feature identifiers and uniqueness", {
  skip_if_not_installed("hdf5r")
  skip_if_not_installed("Seurat")
  skip_if_not_installed("rio")
  path <- tempfile(fileext = ".h5")
  on.exit(unlink(path), add = TRUE)
  file <- hdf5r::H5File$new(path, mode = "w")
  group <- file$create_group("matrix")
  group[["data"]] <- as.numeric(1:6)
  group[["indices"]] <- as.integer(rep(0:2, 2))
  group[["indptr"]] <- c(0L, 3L, 6L)
  group[["shape"]] <- c(3L, 2L)
  group[["barcodes"]] <- c("c1", "c2")
  features <- group$create_group("features")
  features[["id"]] <- c("ENSG1", "ENSG2", "ENSG3")
  features[["name"]] <- c("GENE_A", "GENE_A", "GENE_C")
  features[["feature_type"]] <- rep("Gene Expression", 3L)
  features[["genome"]] <- rep("test", 3L)
  file$close_all()
  expect_equal(sn_read(path, use.names = FALSE),
    Seurat::Read10X_h5(path, use.names = FALSE))
  expect_equal(sn_read(path, unique.features = FALSE),
    Seurat::Read10X_h5(path, unique.features = FALSE))
})
