test_that("QS2 resolves BPCells layers relative to the snapshot and verifies their content", {
  skip_if_not_installed("BPCells")
  skip_if_not_installed("qs2")
  skip_if_not_installed("rio")
  skip_if_not_installed("SeuratObject")
  base <- tempfile()
  on.exit(unlink(base, recursive = TRUE), add = TRUE)
  old <- file.path(base, "original")
  new <- file.path(base, "moved")
  matrix <- Matrix::Matrix(matrix(c(1, 0, 2, 3), 2,
    dimnames = list(c("a", "b"), c("x", "y"))), sparse = TRUE)
  matrix <- methods::as(matrix, "generalMatrix")
  object <- SeuratObject::CreateSeuratObject(matrix)
  convert <- function(object, root) sn_set_layer_backend(object, "bpcells",
    file.path(root, "sidecars"), verbose = FALSE)
  disk <- convert(object, old)
  counts <- SeuratObject::LayerData(disk, layer = "counts")
  SeuratObject::LayerData(disk, layer = "data") <- log1p(counts)
  saved <- file.path(old, "objects", "test.qs2")
  sn_write(disk, saved, auto_install = FALSE)
  expect_true(file.rename(old, new))
  moved <- file.path(new, "objects", "test.qs2")
  expect_equal(as.matrix(SeuratObject::LayerData(sn_read(moved), layer = "counts")),
               as.matrix(matrix))
  other <- SeuratObject::CreateSeuratObject(matrix * 10)
  convert(other, old)
  writeLines("laboratory note", file.path(new, "sidecars", "RNA", "counts", "owner.txt"))
  restored <- sn_read(moved)
  expect_equal(as.matrix(SeuratObject::LayerData(restored, layer = "data")),
               log1p(as.matrix(matrix)))
  expect_identical(unname(restored@misc$bpcells_layers[[1]]),
                   normalizePath(file.path(new, "sidecars", "RNA", "counts")))
  convert(other, file.path(base, "other"))
  unlink(file.path(new, "sidecars"), recursive = TRUE)
  expect_error(sn_read(moved), "identity")
  expect_true(file.rename(file.path(base, "other", "sidecars"), file.path(new, "sidecars")))
  expect_error(sn_read(moved), "identity")
})

test_that("legacy QS2 BPCells backings support explicit source-to-directory rebinding", {
  skip_if_not_installed("BPCells")
  skip_if_not_installed("qs2")
  skip_if_not_installed("rio")
  skip_if_not_installed("SeuratObject")
  base <- tempfile()
  on.exit(unlink(base, recursive = TRUE), add = TRUE)
  matrix <- Matrix::Matrix(matrix(1:6, 2, dimnames = list(c("a", "b"), letters[1:3])), sparse = TRUE)
  object <- sn_set_layer_backend(SeuratObject::CreateSeuratObject(matrix), "bpcells",
    file.path(base, "backing"), verbose = FALSE)
  file <- file.path(base, "legacy.qs2")
  qs2::qs_save(object, file)
  expect_warning(sn_read(file), "legacy|Legacy")
  old <- object@misc$bpcells_layers[[1]]
  new <- file.path(base, "elsewhere")
  expect_true(file.rename(old, new))
  expect_error(sn_read(file), "bpcells_paths")
  fixed <- sn_read(file, bpcells_paths = stats::setNames(new, old))
  expect_equal(as.matrix(SeuratObject::LayerData(fixed, layer = "counts")), as.matrix(matrix))
})

test_that("overwrite protects ordinary directories and user files alongside a BPCells matrix", {
  skip_if_not_installed("BPCells")
  skip_if_not_installed("rio")
  skip_if_not_installed("SeuratObject")
  base <- tempfile()
  on.exit(unlink(base, recursive = TRUE), add = TRUE)
  target <- file.path(base, "RNA", "counts")
  dir.create(target, recursive = TRUE)
  payload <- file.path(target, "owner.txt")
  writeLines("retain me", payload)
  counts <- Matrix::Matrix(matrix(1:4, 2, dimnames = list(c("a", "b"), c("x", "y"))), sparse = TRUE)
  object <- SeuratObject::CreateSeuratObject(counts)
  convert <- function() sn_set_layer_backend(object, "bpcells", base, overwrite = TRUE, verbose = FALSE)
  expect_error(convert(), "BPCells")
  expect_identical(readLines(payload), "retain me")
  expect_error(sn_write(counts, target, to = "bpcells", overwrite = TRUE), "BPCells")
  expect_identical(readLines(payload), "retain me")
  unlink(target, recursive = TRUE)
  convert()
  writeLines("retain me", payload)
  expect_error(convert(), "unrecognized|unrelated")
  expect_identical(readLines(payload), "retain me")
})

test_that("QS2 fingerprints preserve unnamed matrices and lazy row selection", {
  skip_if_not_installed("BPCells")
  skip_if_not_installed("qs2")
  skip_if_not_installed("rio")
  base <- tempfile()
  dir.create(base)
  on.exit(unlink(base, recursive = TRUE), add = TRUE)
  source <- Matrix::Matrix(matrix(1:9, 3L), sparse = TRUE)
  disk <- BPCells::write_matrix_dir(source, file.path(base, "source"), compress = FALSE)
  lazy <- BPCells::t(disk)[c(2L, 1L), , drop = FALSE]
  file <- file.path(base, "subset.qs2")
  sn_write(lazy, file, auto_install = FALSE)
  moved <- file.path(base, "renamed")
  expect_true(file.rename(disk@dir, moved))
  restored <- sn_read(file, bpcells_paths = stats::setNames(moved, disk@dir))
  expect_equal(as.matrix(restored), t(as.matrix(source))[c(2L, 1L), , drop = FALSE])
  expect_equal(dimnames(restored), dimnames(lazy))
})
