test_that("program identities survive punctuation and constant programs", {
  skip_if_not_installed("Seurat")
  m <- rbind(G1=seq(2,16,2), G2=rep(seq(102,108,2),2), G3=rep(2,8))
  colnames(m) <- paste0("c",1:8)
  o <- SeuratObject::CreateSeuratObject(Matrix::Matrix(m,sparse=TRUE))
  o$sample <- rep(paste0("S",1:4),each=2)
  o$condition <- rep(c("control","treated"),each=4)
  o$group <- rep(c("x.y","x"),4)
  o <- sn_score_programs(o,list(z="G1",y.z="G2",constant="G3"),method="mean",layer="counts",result_id="scores")
  a <- sn_test_programs(o,"scores",condition_by="condition",sample_by="sample",group_by="group",return_object=FALSE)
  expect_equal(nrow(a$tables$primary),6)
  expect_equal(subset(a$tables$primary,group=="x.y" & program=="z")$estimate,-8)
  expect_true(all(is.na(subset(a$tables$primary,program=="constant")$p_value)))
})
test_that("AnnData imports require complete cells and align by identity", {
  skip_if_not_installed("Seurat")
  o <- SeuratObject::pbmc_small
  f <- tempfile(fileext=".csv"); on.exit(unlink(f))
  d <- data.frame(UMAP_1=seq_len(ncol(o)),UMAP_2=seq_len(ncol(o)),row.names=rev(colnames(o)))
  write.csv(d[-1,],f)
  expect_error(sn_add_data_from_anndata(o,umap_path=f),"cell")
  write.csv(d,f)
  out <- sn_add_data_from_anndata(o,umap_path=f)
  expect_identical(colnames(out),colnames(o))
  expect_equal(unname(SeuratObject::Embeddings(out[["umap"]])[,1]),rev(seq_len(ncol(o))))
})
test_that("feature scales and blend retain Seurat semantics", {
  skip_if_not_installed("Seurat")
  o <- SeuratObject::pbmc_small; o$cohort <- rep(c("A","B"),each=40)
  o$score <- c(seq(0,1,length.out=40),seq(0,100,length.out=40))
  p <- sn_plot_feature(o,"score",split_by="cohort",keep_scale="feature",raster=FALSE)
  for (q in .sn_patchwork_leaf_plots(p)) expect_equal(ggplot2::ggplot_build(q)$plot$scales$get_scales("colour")$get_limits(),c(0,100))
  expect_no_error(sn_plot_feature(o,"score",keep_scale="none",raster=FALSE))
  p <- sn_plot_feature(o,rownames(o)[1:2],blend=TRUE,raster=FALSE)
  expect_no_error(patchwork::patchworkGrob(p))
  p <- sn_plot_feature(o,rownames(o)[1:4],ncol=1,raster=FALSE)
  expect_equal(p$patches$layout$ncol,1)
  p <- sn_plot_dim(o,reduction="pca",dims=c(2,3),cols=c("red","green","blue"),raster=FALSE,show_axis=TRUE)
  q <- .sn_patchwork_leaf_plots(p)[[1]]
  expect_equal(q$labels$x,"PCA 2")
  expect_setequal(unique(ggplot2::ggplot_build(q)$data[[1]]$colour),c("red","green","blue"))
})
test_that("Python artifacts retain earlier metadata and reject reused IDs", {
  skip_if_not_installed("Seurat")
  o <- SeuratObject::pbmc_small
  root <- tempfile(); dir.create(root); on.exit(unlink(root,recursive=TRUE))
  jsonlite::write_json(list(method="cell2location",n_cells=ncol(o),n_features=nrow(o)),file.path(root,"manifest.json"),auto_unbox=TRUE)
  query <- list(cells=colnames(o),features=rownames(o),n_cells=ncol(o),n_features=nrow(o),layer="counts")
  write.csv(data.frame(typeA=seq_len(ncol(o)),row.names=colnames(o)),file.path(root,"obs.csv"))
  a <- .sn_import_python_object_results(o,"cell2location","one",root,root,"RNA",query,retain_run_dir=FALSE)
  write.csv(data.frame(typeA=rep(100,ncol(o)),row.names=colnames(o)),file.path(root,"obs.csv"))
  b <- .sn_import_python_object_results(a,"cell2location","two",root,root,"RNA",query,retain_run_dir=FALSE)
  old <- b@misc$cell2location$one$imported_metadata
  new <- b@misc$cell2location$two$imported_metadata
  expect_false(identical(old,new))
  expect_equal(b[[old,drop=TRUE]],a[[old,drop=TRUE]])
  expect_true(all(b[[new,drop=TRUE]]==100))
  expect_error(.sn_import_python_object_results(b,"cell2location","one",root,root,"RNA",query),"already exists")
})
test_that("ordinary marker tests preserve upstream rows and tested background", {
  skip_if_not_installed("Seurat")
  set.seed(717)
  m <- matrix(rpois(90*80,2),90,dimnames=list(paste0("g",1:90),paste0("c",1:80)))
  m[1:10,1:40] <- m[1:10,1:40]+8
  o <- Seurat::NormalizeData(SeuratObject::CreateSeuratObject(Matrix::Matrix(m,sparse=TRUE)),verbose=FALSE)
  o$group <- rep(c("A","B"),each=40)
  for (method in c("t","wilcox")) {
    a <- sn_find_de(o,analysis="markers",method=method,group_by="group",min_pct=0,logfc_threshold=0,only_pos=FALSE,verbose=FALSE,return_object=FALSE)
    b <- Seurat::FindAllMarkers(o,group.by="group",test.use=method,min.pct=0,logfc.threshold=0,only.pos=FALSE,verbose=FALSE)
    expect_setequal(a$tables$primary$gene,b$gene)
    expect_equal(nrow(a$tables$primary),nrow(b))
    expect_true(length(a$input$tested_features)>0)
  }
})
